function expectBits(value: Vec3, expected: readonly [number, number, number]): void {
  for (const [actual, bits] of [[value.x, expected[0]], [value.y, expected[1]], [value.z, expected[2]]] satisfies readonly (readonly [number, number])[]) {
    const reference = new DataView(new ArrayBuffer(4)); reference.setInt32(0, bits);
    if (Number.isNaN(reference.getFloat32(0))) expect(Number.isNaN(actual)).toBe(true);
    else {
      const observed = new DataView(new ArrayBuffer(4)); observed.setFloat32(0, actual);
      expect(observed.getInt32(0)).toBe(bits);
    }
  }
}

